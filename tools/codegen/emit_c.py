"""C ABI: core/src/capi/<module>_c.h and .cpp, plus core/include/dazzle_updater.h."""

from __future__ import annotations

from .docs import blocks, line_comment
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, c_function

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"

# Hand-written runtime headers every generated header builds on.
RUNTIME_HEADERS = ["common_c.h", "string_utils_c.h"]

_C_PARAM = {BOOL: "bool", I32: "int32_t", I64: "int64_t", F64: "double", STRING: "const char*"}
_C_RETURN = {VOID: "void", BOOL: "bool", I32: "int32_t", I64: "int64_t", F64: "double", STRING: "char*"}
_ON_EXCEPTION = {BOOL: "false", I32: "0", I64: "0", F64: "0.0", STRING: "nullptr"}


def _signature(cls: Class, method: Method) -> str:
    params = ", ".join(f"{_C_PARAM[p.type]} {p.name}" for p in method.params) or "void"
    return f"{_C_RETURN[method.returns]} {c_function(cls, method)}({params})"


def _refs(cls: Class) -> dict[str, str]:
    return {m.name: c_function(cls, m) + "()" for m in cls.methods}


def _c_doc(cls: Class, method: Method) -> list[str]:
    paragraphs = blocks(method.doc, _refs(cls), params=False, returns=False)[:1]
    if any(p.type == STRING for p in method.params):
        paragraphs.append("String parameters accept NULL as an empty string.")
    if method.returns == STRING:
        paragraphs.append(
            "Returns NULL for an empty string. Caller owns the returned string;\n"
            "free it with dazzle_free_c_str()."
        )
    return line_comment("/// ", paragraphs)


def header(cls: Class) -> str:
    out = [BANNER, "#pragma once", "", '#include "common_c.h"', "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for method in cls.methods:
        out += [*_c_doc(cls, method), "DAZZLE_EXPORT", _signature(cls, method) + ";", ""]
    out += ["#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(out)


def _argument(param) -> str:
    return f"std::string({param.name} ? {param.name} : \"\")" if param.type == STRING else param.name


def source(cls: Class) -> str:
    out = [BANNER, f'#include "{cls.module}_c.h"', "", "#include <cstdio>", "#include <string>", "",
           f'#include "../{cls.header}"', '#include "string_utils_c.h"', ""]
    for method in cls.methods:
        call = (f"{cls.namespace}::{cls.name}::GetInstance().{method.name}("
                + ", ".join(_argument(p) for p in method.params) + ")")
        if method.returns == VOID:
            body = f"    {call};"
        elif method.returns == STRING:
            body = f"    return {cls.namespace}::to_c_str({call});"
        else:
            body = f"    return {call};"
        fallback = _ON_EXCEPTION.get(method.returns)
        out += [
            _signature(cls, method) + " {",
            "  try {",
            body,
            "  } catch (...) {",
            f'    fprintf(stderr, "[dazzle_updater] %s: unexpected exception\\n", "{c_function(cls, method)}");',
            *([f"    return {fallback};"] if fallback else []),
            "  }",
            "}",
            "",
        ]
    return "\n".join(out)


def umbrella(classes: list[Class]) -> str:
    out = [BANNER, "#pragma once", "", "#ifdef __cplusplus", "// C++ API"]
    out += [f'#include "../src/{h}"' for h in sorted({c.header for c in classes})]
    out += ["#endif", "", "// C API (usable from both C and C++)"]
    capi = RUNTIME_HEADERS + [f"{c.module}_c.h" for c in classes]
    out += [f'#include "../src/capi/{h}"' for h in sorted(capi)]
    return "\n".join(out) + "\n"
