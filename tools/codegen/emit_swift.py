"""Swift: stateless, Sendable singleton wrappers over the imported C ABI."""

from __future__ import annotations

from .docs import blocks, line_comment, method_blocks, property_blocks
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, c_function, snake

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"
_PARAM = {BOOL: "Bool", I32: "Int32", I64: "Int64", F64: "Double", STRING: "String"}
_RETURN = {VOID: "Void", **_PARAM, STRING: "String?"}


def _name(name: str) -> str:
    parts = snake(name).split("_")
    return parts[0] + "".join(p.upper() if p in {"url", "ui", "id"} else p.capitalize()
                              for p in parts[1:])


def _call(cls: Class, method: Method, args: dict[str, str]) -> str:
    call = c_function(cls, method) + "(" + ", ".join(
        f"{_name(p.name)}Pointer" if p.type == STRING else args[p.name]
        for p in method.params
    ) + ")"
    if method.returns == STRING:
        call = f"takeCString({call})"
    for param in reversed([p for p in method.params if p.type == STRING]):
        call = f"({args[param.name]}).withCString {{ {_name(param.name)}Pointer in {call} }}"
    return call


def module(cls: Class) -> str:
    properties, actions = cls.properties_and_actions()
    refs = {a.name: f"{_name(a.name)}()" for a in actions}
    for prop in properties:
        name = _name(("Is" if prop.is_bool else "") + prop.name)
        refs[prop.getter.name] = name
        if prop.setter:
            refs[prop.setter.name] = name
    out = [BANNER, "import CDazzleUpdater", "",
           *line_comment("/// ", blocks(cls.doc, refs)),
           f"public final class {cls.name}: Sendable {{",
           "    /// The process-wide instance.",
           f"    public static let shared = {cls.name}()", "",
           "    private init() {}"]
    for prop in properties:
        out += ["", *line_comment("    /// ", property_blocks(prop, refs, "`nil`")),
                f"    public var {refs[prop.getter.name]}: {_RETURN[prop.type]} {{"]
        call = _call(cls, prop.getter, {})
        if prop.setter:
            value = 'newValue ?? ""' if prop.type == STRING else "newValue"
            setter = _call(cls, prop.setter, {prop.setter.params[0].name: value})
            out += [f"        get {{ {call} }}", f"        set {{ {setter} }}"]
        else:
            out += [f"        {call}"]
        out.append("    }")
    for action in actions:
        params = ", ".join(f"_ `{_name(p.name)}`: {_PARAM[p.type]}" for p in action.params)
        args = {p.name: f"`{_name(p.name)}`" for p in action.params}
        result = "" if action.returns == VOID else f" -> {_RETURN[action.returns]}"
        out += ["", *line_comment("    /// ", method_blocks(action, refs, "`nil`")),
                f"    public func {_name(action.name)}({params}){result} {{",
                f"        {_call(cls, action, args)}", "    }"]
    out.append("}")
    return "\n".join(out) + "\n"
