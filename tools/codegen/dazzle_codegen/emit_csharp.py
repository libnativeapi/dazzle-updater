"""C#: bindings/csharp/src/NativeMethods.cs and src/<Class>.cs."""

from __future__ import annotations

import re
from html import escape

from .docs import blocks, property_blocks
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, c_function, camel, pascal
from .parser import join_lines

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"

_NATIVE_PARAM = {BOOL: "bool", I32: "int", I64: "long", F64: "double", STRING: "string?"}
_NATIVE_RETURN = {VOID: "void", BOOL: "bool", I32: "int", I64: "long", F64: "double", STRING: "nint"}
_PARAM = {BOOL: "bool", I32: "int", I64: "long", F64: "double", STRING: "string"}
_RETURN = {VOID: "void", BOOL: "bool", I32: "int", I64: "long", F64: "double", STRING: "string?"}


def _doc_text(text: str) -> str:
    """Escapes XML, then turns Markdown `code` into <c>code</c>."""
    return re.sub(r"`([^`]+)`", r"<c>\1</c>", escape(text, quote=False))


def _xml(indent: str, paragraphs: list[str], params: dict[str, str] | None = None,
         returns: str = "") -> list[str]:
    def text(paragraph: str) -> list[str]:
        return [f"{indent}/// {_doc_text(line)}".rstrip() for line in paragraph.split("\n")]

    if not paragraphs:
        return []
    out = [f"{indent}/// <summary>", *text(paragraphs[0]), f"{indent}/// </summary>"]
    if paragraphs[1:]:
        out.append(f"{indent}/// <remarks>")
        for paragraph in paragraphs[1:]:
            out += [f"{indent}/// <para>", *text(paragraph), f"{indent}/// </para>"]
        out.append(f"{indent}/// </remarks>")
    for name, description in (params or {}).items():
        out.append(f'{indent}/// <param name="{name}">{_doc_text(join_lines(description))}</param>')
    if returns:
        out.append(f"{indent}/// <returns>{_doc_text(returns)}</returns>")
    return out


def native_methods(classes: list[Class]) -> str:
    out = [BANNER, "using System.Runtime.InteropServices;", "", "namespace Dazzle;", "",
           "/// <summary>", "/// Declarations of the dazzle C ABI (<c>core/src/capi/</c>).", "/// </summary>",
           "internal static partial class NativeMethods", "{", '    private const string Library = "dazzle";',
           "", "    // string_utils_c.h", "", "    [LibraryImport(Library)]",
           "    internal static partial void dazzle_free_c_str(nint str);"]
    for cls in classes:
        out += ["", f"    // {cls.module}_c.h"]
        for method in cls.methods:
            strings = any(p.type == STRING for p in method.params)
            attribute = "[LibraryImport(Library, StringMarshalling = StringMarshalling.Utf8)]" if strings \
                else "[LibraryImport(Library)]"
            params = ", ".join(
                ("[MarshalAs(UnmanagedType.U1)] " if p.type == BOOL else "")
                + f"{_NATIVE_PARAM[p.type]} {camel(p.name)}"
                for p in method.params
            )
            out += ["", f"    {attribute}"]
            if method.returns == BOOL:
                out.append("    [return: MarshalAs(UnmanagedType.U1)]")
            out.append(f"    internal static partial {_NATIVE_RETURN[method.returns]} "
                       f"{c_function(cls, method)}({params});")
    out.append("}")
    return "\n".join(out) + "\n"


def _call(cls: Class, method: Method, args: dict[str, str]) -> str:
    call = f"NativeMethods.{c_function(cls, method)}(" + ", ".join(
        f"CString.TruncateAtNul({args[p.name]})" if p.type == STRING else args[p.name]
        for p in method.params
    ) + ")"
    return f"CString.Take({call})" if method.returns == STRING else call


def _refs(cls: Class) -> dict[str, str]:
    """C++ method name -> how C# code refers to it."""
    properties, actions = cls.properties_and_actions()
    refs = {a.name: f"{pascal(a.name)}()" for a in actions}
    for prop in properties:
        name = ("Is" + prop.name) if prop.is_bool else pascal(prop.name)
        refs[prop.getter.name] = name
        if prop.setter:
            refs[prop.setter.name] = name
    return refs


def module(cls: Class) -> str:
    properties, actions = cls.properties_and_actions()
    refs = _refs(cls)
    out = [BANNER, "namespace Dazzle;", "", *_xml("", blocks(cls.doc, refs)), f"public sealed class {cls.name}",
           "{", f"    private {cls.name}()", "    {", "    }", "",
           "    /// <summary>The process-wide instance.</summary>",
           f"    public static {cls.name} Instance {{ get; }} = new();"]
    for prop in properties:
        name = ("Is" + prop.name) if prop.is_bool else pascal(prop.name)
        out += ["", *_xml("    ", property_blocks(prop, refs, "`null`")),
                f"    public {_RETURN[prop.type]} {name}", "    {",
                f"        get => {_call(cls, prop.getter, {})};"]
        if prop.setter:
            out.append(f"        set => {_call(cls, prop.setter, {prop.setter.params[0].name: 'value'})};")
        out.append("    }")
    for action in actions:
        doc = blocks(action.doc, refs, params=False, returns=False)
        params = {camel(n): t for n, t in action.doc.params.items()}
        returns = join_lines(action.doc.returns) if action.doc.returns else ""
        if action.returns == STRING:
            returns = (returns + " " if returns else "") + "An empty string comes back as `null`."
        args = {p.name: camel(p.name) for p in action.params}
        signature = ", ".join(f"{_PARAM[p.type]} {camel(p.name)}" for p in action.params)
        out += ["", *_xml("    ", doc, params, returns),
                f"    public {_RETURN[action.returns]} {pascal(action.name)}({signature}) =>",
                f"        {_call(cls, action, args)};"]
    out.append("}")
    return "\n".join(out) + "\n"
