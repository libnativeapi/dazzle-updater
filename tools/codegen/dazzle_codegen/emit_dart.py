"""Dart: bindings/dart/lib/src/dazzle_bindings.dart, lib/src/<module>.dart and lib/src/modules.dart."""

from __future__ import annotations

from .docs import blocks, line_comment, method_blocks, property_blocks
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, Param, c_function, camel

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"

_NATIVE = {VOID: "Void", BOOL: "Bool", I32: "Int32", I64: "Int64", F64: "Double", STRING: "Pointer<Char>"}
_FFI_DART = {VOID: "void", BOOL: "bool", I32: "int", I64: "int", F64: "double", STRING: "Pointer<Char>"}
_PARAM = {BOOL: "bool", I32: "int", I64: "int", F64: "double", STRING: "String"}
_RETURN = {VOID: "void", BOOL: "bool", I32: "int", I64: "int", F64: "double", STRING: "String?"}


def bindings(classes: list[Class]) -> str:
    out = [
        BANNER.rstrip("\n"),
        "//",
        "// Declarations of the dazzle C ABI (core/src/capi/). The library is the code",
        "// asset built by hook/build.dart, resolved through this file's default asset id.",
        "//",
        "// Declarations keep the C symbol names.",
        "// ignore_for_file: non_constant_identifier_names",
        "@DefaultAsset('package:dazzle/src/dazzle_bindings.dart')",
        "library;",
        "",
        "import 'dart:ffi';",
        "",
        "// string_utils_c.h",
        "",
        "@Native<Void Function(Pointer<Char>)>()",
        "external void dazzle_free_c_str(Pointer<Char> str);",
    ]
    for cls in classes:
        out += ["", f"// {cls.module}_c.h"]
        for method in cls.methods:
            native = ", ".join(_NATIVE[p.type] for p in method.params)
            params = ", ".join(f"{_FFI_DART[p.type]} {p.name}" for p in method.params)
            out += ["", f"@Native<{_NATIVE[method.returns]} Function({native})>()",
                    f"external {_FFI_DART[method.returns]} {c_function(cls, method)}({params});"]
    return "\n".join(out) + "\n"


def _call(cls: Class, method: Method, args: dict[str, str]) -> str:
    """The expression calling `method`, converting strings on the way in and out.

    `args` maps each C++ parameter name to the Dart expression passed for it.
    """
    call = c_function(cls, method) + "(" + ", ".join(
        f"{camel(p.name)}Ptr" if p.type == STRING else args[p.name] for p in method.params
    ) + ")"
    if method.returns == STRING:
        call = f"takeCString({call})"
    for param in reversed([p for p in method.params if p.type == STRING]):
        call = f"withCString({args[param.name]}, ({camel(param.name)}Ptr) => {call})"
    return call


def _params(params: list[Param]) -> str:
    return ", ".join(f"{_PARAM[p.type]} {camel(p.name)}" for p in params)


def _refs(cls: Class) -> dict[str, str]:
    """C++ method name -> how Dart code refers to it."""
    properties, actions = cls.properties_and_actions()
    refs = {a.name: f"{camel(a.name)}()" for a in actions}
    for prop in properties:
        name = ("is" + prop.name) if prop.is_bool else camel(prop.name)
        refs[prop.getter.name] = name
        if prop.setter:
            refs[prop.setter.name] = name
    return refs


def module(cls: Class) -> str:
    properties, actions = cls.properties_and_actions()
    refs = _refs(cls)
    uses_strings = any(
        m.returns == STRING or any(p.type == STRING for p in m.params) for m in cls.methods
    )
    out = [BANNER, "import 'dazzle_bindings.dart';"]
    if uses_strings:
        out.append("import 'ffi_string.dart';")
    out += ["", *line_comment("/// ", blocks(cls.doc, refs)), f"final class {cls.name} {{",
            f"  {cls.name}._();", "", "  /// The process-wide instance.",
            f"  static final {cls.name} instance = {cls.name}._();"]
    for prop in properties:
        name = ("is" + prop.name) if prop.is_bool else camel(prop.name)
        type_ = _RETURN[prop.type]
        out += ["", *line_comment("  /// ", property_blocks(prop, refs, "`null`")),
                f"  {type_} get {name} => {_call(cls, prop.getter, {})};"]
        if prop.setter:
            param = prop.setter.params[0]
            value = "value ?? ''" if prop.type == STRING else "value"
            out += ["", f"  set {name}({type_} value) =>",
                    f"      {_call(cls, prop.setter, {param.name: value})};"]
    for action in actions:
        args = {p.name: camel(p.name) for p in action.params}
        out += ["", *line_comment("  /// ", method_blocks(action, refs, "`null`")),
                f"  {_RETURN[action.returns]} {camel(action.name)}({_params(action.params)}) =>",
                f"      {_call(cls, action, args)};"]
    out.append("}")
    return "\n".join(out) + "\n"


def library(classes: list[Class]) -> str:
    """lib/dazzle.dart: the package's entry file, one export per generated class."""
    out = [BANNER, "/// A cross-platform software update framework.", "library;", ""]
    out += [f"export 'src/{cls.module}.dart' show {cls.name};" for cls in classes]
    return "\n".join(out) + "\n"
