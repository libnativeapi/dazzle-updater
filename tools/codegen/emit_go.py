"""Go: bindings/go/<module>.go, calling the generated C ABI through cgo."""

from __future__ import annotations

from .docs import blocks, line_comment, method_blocks
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, c_function, camel, snake

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"

_TYPE = {BOOL: "bool", I32: "int32", I64: "int64", F64: "float64", STRING: "string"}
_C_TYPE = {BOOL: "C.bool", I32: "C.int32_t", I64: "C.int64_t", F64: "C.double"}
_INITIALISMS = {"url": "URL", "ui": "UI", "http": "HTTP", "https": "HTTPS", "id": "ID"}
_KEYWORDS = set("break default func interface select case defer go map struct chan else goto "
                "package switch const fallthrough if range type continue for import return var".split())


def _exported(name: str) -> str:
    return "".join(_INITIALISMS.get(part, part.capitalize()) for part in snake(name).split("_"))


def _param(name: str) -> str:
    name = camel(name)
    return name + "Value" if name in _KEYWORDS else name


def _names(cls: Class) -> dict[str, str]:
    properties, actions = cls.properties_and_actions()
    names = {m.name: _exported(m.name) for m in actions}
    for prop in properties:
        names[prop.getter.name] = ("Is" if prop.is_bool else "") + _exported(prop.name)
        if prop.setter:
            names[prop.setter.name] = "Set" + _exported(prop.name)
    return names


def _method(cls: Class, method: Method, name: str, refs: dict[str, str]) -> list[str]:
    params = ", ".join(f"{_param(p.name)} {_TYPE[p.type]}" for p in method.params)
    ret = " " + _TYPE[method.returns] if method.returns != VOID else ""
    body = []
    args = []
    # Choose temporary names independently of the header's parameter names.
    used = {_param(p.name) for p in method.params}
    for i, param in enumerate(method.params):
        value = _param(param.name)
        if param.type == STRING:
            temp = f"cArg{i}"
            while temp in used:
                temp += "_"
            used.add(temp)
            body += [f"{temp} := toCString({value})", f"defer freeCString({temp})"]
            args.append(temp)
        else:
            args.append(f"{_C_TYPE[param.type]}({value})")
    call = f"C.{c_function(cls, method)}({', '.join(args)})"
    if method.returns == STRING:
        body.append(f"return takeCString({call})")
    elif method.returns != VOID:
        body.append(f"return {_TYPE[method.returns]}({call})")
    else:
        body.append(call)
    doc = method_blocks(method, refs, '`""`')
    if doc:
        doc[0] = name + ": " + doc[0]
    return [*line_comment("// ", doc), f"func (*{cls.name}) {name}({params}){ret} {{",
            *(f"\t{line}" for line in body), "}"]


def module(cls: Class) -> str:
    names = _names(cls)
    refs = {cpp: f"{go}()" for cpp, go in names.items()}
    instance = camel(cls.name) + "Instance"
    doc = blocks(cls.doc, refs)
    if doc:
        doc[0] = cls.name + ": " + doc[0]
    doc.append("All values of this type use the same process-wide native instance.")
    out = [BANNER.rstrip(), "// Code generated by tools/codegen. DO NOT EDIT.", "",
           "package dazzleupdater", "", "// #include <dazzle_updater.h>", 'import "C"', "",
           *line_comment("// ", doc), f"type {cls.name} struct{{}}", "",
           f"var {instance} = &{cls.name}{{}}", "",
           f"// {cls.name}Instance returns the process-wide {cls.name} instance.",
           f"func {cls.name}Instance() *{cls.name} {{", f"\treturn {instance}", "}"]
    properties, actions = cls.properties_and_actions()
    ordered = [m for p in properties for m in (p.getter, p.setter) if m] + actions
    for method in ordered:
        out += ["", *_method(cls, method, names[method.name], refs)]
    return "\n".join(out) + "\n"
