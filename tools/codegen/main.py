"""Entry point: ./codegen [generate|check]."""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from . import emit_c, emit_csharp, emit_dart, emit_rust
from .model import Class
from .parser import Warnings, parse_header

# The public headers under core/src/ exported through the C ABI. Append new modules here.
API_HEADERS = [
    "updater.h",
    "release_index_source.h",
    "updater_ui.h",
]

BANNER = "AUTO-GENERATED by tools/codegen. DO NOT EDIT."

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "core"
RUST = ROOT / "bindings" / "rust"
DART = ROOT / "bindings" / "dart"
CSHARP = ROOT / "bindings" / "csharp"

# Directories whose generated files (those carrying BANNER) this tool owns.
OUTPUT_DIRS = [CORE / "src" / "capi", CORE / "include", RUST / "src",
               DART / "lib", DART / "lib" / "src", CSHARP / "src"]


def generate(classes: list[Class]) -> dict[Path, str]:
    files: dict[Path, str] = {CORE / "include" / "dazzle_updater.h": emit_c.umbrella(classes)}
    for cls in classes:
        files[CORE / "src" / "capi" / f"{cls.module}_c.h"] = emit_c.header(cls)
        files[CORE / "src" / "capi" / f"{cls.module}_c.cpp"] = emit_c.source(cls)
        files[RUST / "src" / f"{cls.module}.rs"] = emit_rust.module(cls)
        files[DART / "lib" / "src" / f"{cls.module}.dart"] = emit_dart.module(cls)
        files[CSHARP / "src" / f"{cls.name}.cs"] = emit_csharp.module(cls)
    files[RUST / "src" / "ffi.rs"] = emit_rust.ffi(classes)
    files[RUST / "src" / "modules.rs"] = emit_rust.modules(classes)
    files[DART / "lib" / "src" / "dazzle_updater_bindings.dart"] = emit_dart.bindings(classes)
    files[DART / "lib" / "dazzle_updater.dart"] = emit_dart.library(classes)
    files[CSHARP / "src" / "NativeMethods.cs"] = emit_csharp.native_methods(classes)
    return _format(files)


def _format(files: dict[Path, str]) -> dict[Path, str]:
    """Runs the language formatters, so formatting a binding never dirties its generated files."""
    for path, content in files.items():
        if path.suffix == ".rs":
            files[path] = _run(["rustfmt", "--edition", "2021"], content)
    dart = {p: c for p, c in files.items() if p.suffix == ".dart"}
    if dart:
        with tempfile.TemporaryDirectory() as tmp:
            temp_paths = {p: Path(tmp) / p.name for p in dart}
            for path, temp in temp_paths.items():
                temp.write_text(dart[path])
            _run(["dart", "format", "--output=write", tmp], "")
            for path, temp in temp_paths.items():
                files[path] = temp.read_text()
    return files


def _run(command: list[str], stdin: str) -> str:
    if not shutil.which(command[0]):
        sys.exit(f"codegen: {command[0]} not found; it is needed to format the generated code")
    result = subprocess.run(command, input=stdin, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"codegen: {' '.join(command)} failed:\n{result.stderr}")
    return result.stdout


def _stale(files: dict[Path, str]) -> list[Path]:
    """Generated files on disk that the current headers no longer produce."""
    stale = []
    for directory in OUTPUT_DIRS:
        for path in sorted(directory.glob("*")):
            if path.is_file() and path not in files and BANNER in path.read_text(errors="ignore")[:200]:
                stale.append(path)
    return stale


def main() -> None:
    parser = argparse.ArgumentParser(prog="codegen", description=__doc__)
    parser.add_argument("command", nargs="?", default="generate", choices=["generate", "check"],
                        help="generate: write the files (default); check: fail if any is out of date")
    args = parser.parse_args()

    warnings = Warnings()
    classes = [cls for header in API_HEADERS for cls in parse_header(CORE / "src", header, warnings)]
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    files = generate(classes)
    changed = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
    stale = _stale(files)

    if args.command == "check":
        for path in changed:
            print(f"out of date: {path.relative_to(ROOT)}")
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        if changed or stale:
            sys.exit("codegen: generated files are out of date; run ./codegen")
        print(f"codegen: {len(files)} generated files are up to date")
        return

    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path])
        print(f"wrote {path.relative_to(ROOT)}")
    for path in stale:
        path.unlink()
        print(f"removed {path.relative_to(ROOT)}")
    print(f"codegen: {len(files)} files, {len(changed)} written, {len(stale)} removed")
