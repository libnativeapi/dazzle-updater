"""Rust: bindings/rust/src/ffi.rs, src/<module>.rs and src/modules.rs."""

from __future__ import annotations

from .docs import blocks, line_comment, method_blocks
from .model import BOOL, F64, I32, I64, STRING, VOID, Class, Method, c_function, snake

BANNER = "// AUTO-GENERATED by tools/codegen. DO NOT EDIT.\n"

_FFI_PARAM = {BOOL: "bool", I32: "i32", I64: "i64", F64: "f64", STRING: "*const c_char"}
_FFI_RETURN = {BOOL: "bool", I32: "i32", I64: "i64", F64: "f64", STRING: "*mut c_char"}
_PARAM = {BOOL: "bool", I32: "i32", I64: "i64", F64: "f64", STRING: "&str"}
_RETURN = {BOOL: "bool", I32: "i32", I64: "i64", F64: "f64", STRING: "Option<String>"}


def ffi(classes: list[Class]) -> str:
    out = [BANNER, "//! Declarations of the dazzle_updater C ABI (`core/src/capi/`).", "",
           "use std::os::raw::c_char;", "", "// string_utils_c.h", 'extern "C" {',
           "    pub fn dazzle_free_c_str(str_: *mut c_char);", "}"]
    for cls in classes:
        out += ["", f"// {cls.module}_c.h", 'extern "C" {']
        for method in cls.methods:
            params = ", ".join(f"{p.name}: {_FFI_PARAM[p.type]}" for p in method.params)
            ret = f" -> {_FFI_RETURN[method.returns]}" if method.returns != VOID else ""
            out.append(f"    pub fn {c_function(cls, method)}({params}){ret};")
        out.append("}")
    return "\n".join(out) + "\n"


def _method(cls: Class, method: Method, name: str, doc: list[str]) -> list[str]:
    params = "".join(f", {p.name}: {_PARAM[p.type]}" for p in method.params)
    ret = f" -> {_RETURN[method.returns]}" if method.returns != VOID else ""
    body = [f"let {p.name} = to_c_string({p.name});" for p in method.params if p.type == STRING]
    args = ", ".join(f"{p.name}.as_ptr()" if p.type == STRING else p.name for p in method.params)
    call = f"ffi::{c_function(cls, method)}({args})"
    body.append(f"unsafe {{ take_c_string({call}) }}" if method.returns == STRING else f"unsafe {{ {call} }}")
    return [*line_comment("    /// ", doc), f"    pub fn {name}(&self{params}){ret} {{",
            *(f"        {line}" for line in body), "    }"]


def _names(cls: Class) -> dict[str, str]:
    """C++ method name -> Rust method name."""
    properties, actions = cls.properties_and_actions()
    names = {a.name: snake(a.name) for a in actions}
    for prop in properties:
        names[prop.getter.name] = ("is_" if prop.is_bool else "") + snake(prop.name)
        if prop.setter:
            names[prop.setter.name] = "set_" + snake(prop.name)
    return names


def module(cls: Class) -> str:
    properties, actions = cls.properties_and_actions()
    names = _names(cls)
    refs = {cpp: f"{rust}()" for cpp, rust in names.items()}
    uses_strings = any(
        m.returns == STRING or any(p.type == STRING for p in m.params) for m in cls.methods
    )
    instance = cls.module.upper()
    out = [BANNER, "use crate::ffi;"]
    if uses_strings:
        out.append("use crate::ffi_string::{take_c_string, to_c_string};")
    out += ["", *line_comment("/// ", blocks(cls.doc, refs)), "#[derive(Debug)]",
            f"pub struct {cls.name} {{", "    _private: (),", "}", "",
            f"static {instance}: {cls.name} = {cls.name} {{ _private: () }};", "",
            f"impl {cls.name} {{", "    /// The process-wide instance.",
            f"    pub fn instance() -> &'static {cls.name} {{", f"        &{instance}", "    }"]
    # Getter before setter, then actions: the order the header declares them is not kept.
    ordered = [m for p in properties for m in (p.getter, p.setter) if m] + actions
    for method in ordered:
        out += ["", *_method(cls, method, names[method.name], method_blocks(method, refs, "`None`"))]
    out.append("}")
    return "\n".join(out) + "\n"


def modules(classes: list[Class]) -> str:
    out = [BANNER.rstrip("\n"), "// Included by lib.rs: one module per generated class.", ""]
    for cls in classes:
        out += [f"mod {cls.module};", f"pub use {cls.module}::{cls.name};"]
    return "\n".join(out) + "\n"
